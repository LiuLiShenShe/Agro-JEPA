def write_protocol(path: Path, p: dict, pcfg: dict) -> None:
    c1 = p["C1_s3_protocol_problem"]
    split = p["C2_plot_split"]
    L = [
        "# S3.2 — corrected E2 probe protocol",
        "",
        f"Stage: **S3.2**. Generated from `{Path(path).with_suffix('.json')}`.",
        "",
        "## 1. C1 — what was wrong with the S3 early stopping",
        "",
        f"File: `{c1['file']}`; functions `{c1['function']}`.",
        "",
        c1["problem"],
        "",
        "Evidence (line numbers in the committed file):",
        "",
        table(["code fact", "lines", "code"],
              [[k, ", ".join(str(x) for x in v["lines"]),
                " / ".join(f"`{c}`" for c in v["code"])]
               for k, v in c1["evidence"].items() if "code" in v]),
        "",
        "Additional split usage: "
        + "; ".join(f"{k} at lines {v['lines']}" for k, v in c1["evidence"].items()
                    if "code" not in v) + ".",
        "",
        "Correction: " + c1["corrected_here"],
        "",
        "## 2. C2 — inner split of the official train plots",
        "",
        table(["Item", "Value"], [
            ["rule", split["rule"]],
            ["seed", split["seed"]],
            ["inner-train fraction", split["inner_train_fraction"]],
            ["strata", split["strata"]],
            ["plots total / inner-train / inner-dev",
             f"{split['n_plots']} / {split['n_inner_train_plots']} / {split['n_inner_dev_plots']}"],
            ["inner-train ∩ inner-dev", not split["disjoint"]],
            ["official validation plots in the split",
             split["official_validation_plots_in_split"]],
            ["split file", f"`{split['file']}`"],
        ]),
        "",
        table(["harvest year", "plots", "inner-train", "inner-dev"],
              [[y, v["n_plots"], v["n_inner_train_plots"], v["n_inner_dev_plots"]]
               for y, v in split["by_year"].items()]),
        "",
        "## 3. Sample counts per condition",
        "",
    ]
    rows = []
    for variant, traits in p["C3_inner_selection"].items():
        for trait, scopes in traits.items():
            for scope, blk in scopes.items():
                if "counts" not in blk:
                    continue
                c = blk["counts"]
                rows.append([variant, trait, scope, c["n_train"], c["n_train_plots"],
                             c["n_inner_train"], c["n_inner_train_plots"],
                             c["n_inner_dev"], c["n_inner_dev_plots"],
                             c["n_val"], c["n_val_plots"], c["lag_max_abs_days"]])
    L += [
        table(["variant", "trait", "scope", "train pairs", "train plots",
               "inner-train pairs", "inner-train plots", "inner-dev pairs",
               "inner-dev plots", "val pairs", "val plots", "abs(lag) ≤ d"],
              rows),
        "",
        "## 4. C3 — inner model selection",
        "",
        "Rule: minimum inner-dev MSE over the candidate budget "
        f"({p['inputs'].get('candidate_epochs', pcfg['candidate_epochs'])} epochs, "
        f"patience {p['inputs'].get('patience', pcfg['patience'])}), the same rule "
        "for A and B.",
        "",
    ]
    rows = []
    for variant, traits in p["C3_inner_selection"].items():
        for trait, scopes in traits.items():
            for scope, blk in scopes.items():
                if "conditions" not in blk:
                    continue
                rows.append([
                    variant, trait, scope,
                    ", ".join(str(e) for e in blk["conditions"]["A_current"]["best_epochs"]),
                    blk["conditions"]["A_current"]["selected_epoch_median"],
                    ", ".join(str(e) for e in blk["conditions"]["B_predicted"]["best_epochs"]),
                    blk["conditions"]["B_predicted"]["selected_epoch_median"],
                    blk["shared_epoch_median_over_both_conditions"],
                ])
    L += [
        table(["variant", "trait", "scope", "A best epochs", "A selected",
               "B best epochs", "B selected", "shared"], rows),
        "",
    ]
    all_best = [
        e
        for traits in p["C3_inner_selection"].values()
        for scopes in traits.values()
        for blk in scopes.values() if "conditions" in blk
        for cond in ("A_current", "B_predicted")
        for e in blk["conditions"][cond]["best_epochs"]
    ]
    L += [
        f"Across all {len(all_best)} inner-dev runs the best epoch ranges "
        f"{min(all_best)}–{max(all_best)}.  The dev loss surface is therefore flat "
        "and the epoch choice is only weakly identified; the shared-epoch control "
        "below is reported for that reason, and no conclusion in this stage rests "
        "on a small epoch difference.",
        "",
        "## 5. C4 — final refit",
        "",
        "After selection the epoch rule is frozen and the readout is retrained on "
        "**all** official-train plots for that trait/scope.  The cosine schedule is "
        "anchored to the same candidate budget as the inner runs, so a final run "
        "stopped at the selected epoch has exactly the parameters a full-budget run "
        "would have at that epoch.  No official-validation target is read during "
        "training or selection.  A shared-epoch variant (same epoch for A and B) is "
        "reported as a sensitivity check.",
        "",
        "Caveat: the V0 checkpoint itself was selected on this validation split in "
        "S3, so this correction removes the *probe-level* early-stopping bias only. "
        "The split is not an untouched test set, and the formal external claim still "
        "requires the official test split.",
        "",
        "### Inputs",
        "",
        table(["Item", "Value"], [[k, v] for k, v in p["inputs"].items()]),
        "",
        "### Alignment check against the S3 aggregates (old protocol re-run)",
        "",
        table(["condition", "recomputed MAE / RMSE / R²", "S3 reference", "within tolerance"],
              [[k,
                f"{f(v['recomputed_old_protocol']['mae'])} / "
                f"{f(v['recomputed_old_protocol']['rmse'])} / "
                f"{f(v['recomputed_old_protocol']['r2'])}",
                f"{f(v['s3_1_reference']['mae'])} / "
                f"{f(v['s3_1_reference']['rmse'])} / "
                f"{f(v['s3_1_reference']['r2'])}",
                v["within_tolerance"]]
               for k, v in p["alignment_check"]["values"].items()]),
        "",
        "## 6. Command",
        "",
        "```bash",
        "CUDA_VISIBLE_DEVICES=1 python3 tools/s3_2_probe_eval.py \\",
        "    --config agro_jepa/config/s3_2_diagnostics.yaml",
        "python3 tools/s3_2_write_reports.py",
        "```",
        "",
        f"Runtime {p['elapsed_seconds']:.0f} s. Per-sample predictions: "
        f"`{p['artifacts']['per_sample_predictions']}` "
        f"({p['artifacts']['n_rows']} rows).",
        "",
    ]
    path.write_text("\n".join(L))


