#!/usr/bin/env python3
"""S3.2 report writer: markdown from the real JSON artifacts only.

Produces
--------
reports/s3_2_delta_diagnostics.md
reports/s3_2_probe_protocol.md
reports/s3_2_probe_results.md

Every number is read from ``reports/s3_2_*.json``; nothing is typed in by hand.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def f(x, nd=5):
    if x is None:
        return "n/a"
    return f"{x:.{nd}f}"


def pct(x, nd=2):
    if x is None:
        return "n/a"
    return f"{100.0 * x:+.{nd}f}%"


def seeds(blk) -> str:
    s = blk.get("seeds") or []
    if not s:
        return "deterministic"
    if len(s) == 1:
        return str(s[0])
    return f"{s[0]}…{s[-1]} ({len(s)})"


def ci(d, nd=2, scale=100.0, unit="%"):
    if not d:
        return "n/a"
    return (
        f"{scale * d['mean']:+.{nd}f}{unit} "
        f"[{scale * d['ci95_low']:+.{nd}f}, {scale * d['ci95_high']:+.{nd}f}]"
    )


def table(headers, rows):
    out = ["| " + " | ".join(str(h) for h in headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def read(path):
    return json.loads(Path(path).read_text())


