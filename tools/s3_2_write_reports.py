def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="agro_jepa/config/s3_2_diagnostics.yaml")
    ap.add_argument("--delta", default="reports/s3_2_delta_diagnostics.json")
    ap.add_argument("--protocol", default="reports/s3_2_probe_protocol.json")
    ap.add_argument("--results", default="reports/s3_2_probe_results.json")
    ap.add_argument("--delta-md", default="reports/s3_2_delta_diagnostics.md")
    ap.add_argument("--protocol-md", default="reports/s3_2_probe_protocol.md")
    ap.add_argument("--results-md", default="reports/s3_2_probe_results.md")
    args = ap.parse_args()

    import yaml

    pcfg = yaml.safe_load(Path(args.config).read_text())["probe"]
    write_delta(Path(args.delta_md), read(args.delta))
    protocol = read(args.protocol)
    write_protocol(Path(args.protocol_md), protocol, pcfg)
    write_results(Path(args.results_md), read(args.results), protocol)
    print(f"wrote {args.delta_md}, {args.protocol_md}, {args.results_md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
