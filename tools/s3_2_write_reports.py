def write_delta(path: Path, d: dict) -> None:
    a0 = d["A0_real_delta"]
    sc = d["scope"]
    conds = d["conditions"]
    L = [
        "# S3.2 — controlled Δt diagnostics (time conditioning)",
        "",
        f"Stage: **S3.2**. Generated by `tools/s3_2_write_reports.py` from "
        f"`{Path(path).with_suffix('.json')}`. No model was retrained; every "
        "condition only replaces the interval fed to the frozen checkpoint.",
        "",
        "## 0. Headline",
        "",
        f"- Reference (real Δt): MSE **{f(a0['mse_real'])}**, persistence "
        f"{f(a0['mse_persist'])}, cosine **{f(a0['cosine_real'])}**.",
        f"- Global permutation (A1): **{pct(conds['A1_global_permutation']['relative_increase_mean'])}** "
        f"(S3.1 reference {pct(d['conditions']['A1_global_permutation']['relative_increase_mean'])}; "
        f"reproduction diff "
        f"{f(a0['matches_s3_1_reference']['mse_real_diff'], 8)} MSE).",
        f"- Same-pair_type permutation (A2): "
        f"**{pct(conds['A2_within_pair_type_permutation']['relative_increase_mean'])}**.",
        f"- Same-pair_type train mean (A3): "
        f"**{pct(conds['A3_pair_type_train_mean']['relative_increase_mean'])}**.",
        f"- Pair_type × harvest_year permutation (A4): "
        f"**{pct(conds['A4_within_pair_type_year_permutation']['relative_increase_mean'])}**.",
        "",
        "## 1. Frozen inputs",
        "",
        table(["Item", "Value"], [
            ["checkpoint", f"`{d['frozen']['checkpoint']}`"],
            ["checkpoint SHA256", f"`{d['frozen']['checkpoint_sha256']}`"],
            ["checkpoint matches S3 record", d["frozen"]["checkpoint_matches"]],
            ["index SHA256", f"`{d['frozen']['index_sha256']}`"],
            ["index matches S3 record", d["frozen"]["index_matches"]],
            ["config", f"`{d['config']}`"],
            ["config SHA256", f"`{d['config_sha256']}`"],
            ["git HEAD at run", f"`{d['git_head']}`"],
            ["device", d["device"]],
        ]),
        "",
        "| Scope | Value |",
        "|---|---|",
        f"| split | {sc['split']} |",
        f"| pairs / plots | {sc['n_samples']} / {sc['n_plots']} |",
        f"| pair types | {', '.join(sc['pair_types'])} |",
        f"| realised Δt range | {sc['delta_range'][0]}–{sc['delta_range'][1]} d |",
        "",
        "Realised Δt counts: "
        + ", ".join(f"{int(float(k))} d: {v}" for k, v in sc["delta_counts"].items())
        + ".",
        "",
    ]

    # A0 parity
    L += [
        "### 1.1 A0 reproduction of the S3 baseline",
        "",
        table(["Quantity", "Value"], [
            ["MSE real Δt", f(a0["mse_real"])],
            ["MSE persistence", f(a0["mse_persist"])],
            ["cosine real Δt", f(a0["cosine_real"])],
            ["relative improvement vs persistence",
             pct(a0["relative_improvement_vs_persistence"])],
            ["MSE difference vs S3.1 reference",
             f(a0["matches_s3_1_reference"]["mse_real_diff"], 9)],
            ["per-sample max |Δ| vs stored S3 parquet",
             f(a0.get("s3_parquet_parity", {}).get("max_abs_diff_mse"), 9)],
        ]),
        "",
    ]

    # main condition table
    rows = []
    for name, blk in conds.items():
        rows.append([
            name,
            f(blk["mse_condition_mean"]),
            f(blk["mse_condition_std"]),
            pct(blk["relative_increase_mean"]),
            f"{pct(blk['relative_increase_min'])} / {pct(blk['relative_increase_max'])}",
            ci(blk["relative_increase_bootstrap"]),
            str(blk["n_seeds"]),
            f"{100 * blk['per_sample_worse_fraction']:.2f}%",
        ])
    L += [
        "## 2. A0–A4: intervention results (validation, 20 seeds where applicable)",
        "",
        table(
            ["condition", "MSE mean", "MSE sd (seeds)", "rel. increase (mean)",
             "min / max across seeds", "95% CI of rel. increase",
             "seeds", "fraction of pairs made worse"],
            rows,
        ),
        "",
        "The 95% CI is a plot-level cluster bootstrap (2,000 resamples of "
        "`plot_uid`, fixed seed) on the paired per-sample MSE difference, "
        "seed-averaged before resampling.",
        "",
        "### 2.1 Per-condition descriptions",
        "",
    ]
    for name, blk in conds.items():
        L.append(f"- **{name}** — {blk.get('description', '')}")
        if "seeds" in blk:
            L.append(f"  - seeds: {seeds(blk)}")
        if "groups" in blk:
            gs = blk["groups"]
            if any(isinstance(v, dict) and not v.get("permuted", True) for v in gs.values()):
                L.append("  - groups too small to permute: "
                         + ", ".join(k for k, v in gs.items()
                                     if isinstance(v, dict) and not v.get("permuted", True)))
            L.append(f"  - multiset preserved in every group: "
                     f"{blk.get('multiset_preserved_all_seeds')}")
        if "train_means" in blk:
            L.append("  - train means: " + ", ".join(
                f"{k}={v:.5f} d" for k, v in blk["train_means"].items()))
            L.append("  - validation means (reference only): " + ", ".join(
                f"{k}={v:.5f} d" for k, v in
                blk["validation_means_for_reference_only"].items()))
    L.append("")

    # by span
    spans = sorted(conds["A1_global_permutation"]["by_span"])
    rows = []
    for sp in spans:
        row = [sp]
        for name in conds:
            b = conds[name]["by_span"][sp]
            row.append(f"{f(b['mse_condition_mean'])} ({pct(b['relative_increase_mean'])})")
        rows.append(row)
    L += [
        "## 3. By nominal span (A0 reference: "
        + ", ".join(f"{sp} {f(conds['A1_global_permutation']['by_span'][sp]['mse_real'])}"
                    for sp in spans) + ")",
        "",
        table(["span"] + list(conds), rows),
        "",
        "Values are MSE (relative increase vs A0).",
        "",
    ]

    # by year
    years = sorted(conds["A1_global_permutation"]["by_year"])
    rows = []
    for y in years:
        row = [y, conds["A1_global_permutation"]["by_year"][y]["n_samples"]]
        for name in conds:
            b = conds[name]["by_year"][y]
            row.append(pct(b["relative_increase_mean"]))
        rows.append(row)
    L += [
        "## 4. By harvest year (relative increase vs A0)",
        "",
        table(["year", "pairs"] + list(conds), rows),
        "",
    ]

    # A5
    L += [
        "## 5. A5 — by realised interval",
        "",
        "No unweighted average across these rows: the interval groups have very "
        "different sample counts and belong to two disjoint span families.",
        "",
    ]
    headers = ["Δt (d)", "pairs", "plots", "MSE A0", "MSE persist",
               "cos A0", "A1", "A2", "A3", "A4"]
    rows = []
    for k, b in d["A5_by_real_delta"].items():
        if b.get("n_samples", 0) == 0:
            rows.append([k, 0, 0, "n/a", "n/a", "n/a", "n/a", "n/a", "n/a", "n/a"])
            continue
        diag = b["diagnostics"]
        rows.append([
            k, b["n_samples"], b["n_plots"], f(b["mse_real"]), f(b["mse_persist"]),
            f(b["cosine_real"], 4),
            pct(diag["A1_global_permutation"]["relative_increase"]),
            pct(diag["A2_within_pair_type_permutation"]["relative_increase"]),
            pct(diag["A3_pair_type_train_mean"]["relative_increase"]),
            pct(diag["A4_within_pair_type_year_permutation"]["relative_increase"]),
        ])
    L += [table(headers, rows), "",
          "MSE columns A1–A4 are the mean over seeds; the percentage is relative to "
          "the A0 MSE of the same interval group.", ""]

    # invariants
    inv = d["invariants"]
    L += [
        "## 6. Invariants",
        "",
        table(["Invariant", "Value"], [
            ["persistence MSE (A0)", f(inv["persistence_mse_real"])],
            ["max |persistence deviation| over all interventions",
             max(inv["max_abs_persist_deviation_by_condition"].values())],
            ["z_a / z_b / pair order unchanged", inv["z_and_pair_order_unchanged"]],
        ]),
        "",
        inv["note"],
        "",
        "## 7. How to read this",
        "",
        "1. **Global permutation (A1)** quantifies how much the model uses the time "
        "channel at all. It destroys both the span class and the exact interval.",
        "2. **Within-pair_type permutation (A2)** keeps every sample in its own span "
        "family and only breaks the sample → exact-interval link. The residual "
        "increase is therefore the part that depends on the precise interval.",
        "3. **Pair_type train mean (A3)** removes all within-class variation while "
        "keeping a correct short/long level. It is the strongest coarse-conditioning "
        "control.",
        "4. **Pair_type × harvest_year permutation (A4)** additionally holds the "
        "year composition fixed, so the A2 result is not explained by year-specific "
        "interval distributions.",
        "5. If A2/A3/A4 are all close to each other, the model is not resolving the "
        "exact interval beyond the span level; the evidence would then support "
        "coarse growth-stage conditioning, not per-sample interval precision.",
        "",
        "## 8. Bounded answer from these numbers",
        "",
        f"- Global loss of interval information (A1): "
        f"**{pct(conds['A1_global_permutation']['relative_increase_mean'])}** "
        f"[{pct(conds['A1_global_permutation']['relative_increase_bootstrap']['ci95_low'])}, "
        f"{pct(conds['A1_global_permutation']['relative_increase_bootstrap']['ci95_high'])}].",
        f"- Part that survives keeping the span class (A2): "
        f"**{pct(conds['A2_within_pair_type_permutation']['relative_increase_mean'])}**.",
        f"- Part attributable to the exact interval beyond the class mean "
        f"(A2 minus A3): **{pct(conds['A2_within_pair_type_permutation']['relative_increase_mean'] - conds['A3_pair_type_train_mean']['relative_increase_mean'])}** "
        f"of MSE; the remaining "
        f"{pct(conds['A3_pair_type_train_mean']['relative_increase_mean'])} is the "
        "coarse level of the interval.",
        f"- Year-stratified permutation (A4) gives "
        f"**{pct(conds['A4_within_pair_type_year_permutation']['relative_increase_mean'])}**, "
        f"{100.0 * (conds['A4_within_pair_type_year_permutation']['relative_increase_mean'] - conds['A2_within_pair_type_permutation']['relative_increase_mean']):+.2f} "
        "percentage points relative to A2, so the within-span result is not a "
        "year-composition artefact.",
        "",
        "A2 vs A3, with their bootstrap intervals "
        f"({pct(conds['A2_within_pair_type_permutation']['relative_increase_bootstrap']['ci95_low'])}–"
        f"{pct(conds['A2_within_pair_type_permutation']['relative_increase_bootstrap']['ci95_high'])} "
        "vs "
        f"{pct(conds['A3_pair_type_train_mean']['relative_increase_bootstrap']['ci95_low'])}–"
        f"{pct(conds['A3_pair_type_train_mean']['relative_increase_bootstrap']['ci95_high'])}): "
        + (
            "the A2 interval lies entirely above the A3 interval, so the model does "
            "carry a small amount of sample-level interval information."
            if conds['A2_within_pair_type_permutation']['relative_increase_bootstrap']['ci95_low']
               > conds['A3_pair_type_train_mean']['relative_increase_bootstrap']['ci95_high']
            else "the intervals overlap, so a sample-level interval effect is **not** "
                 "separated from the coarse-level effect by this experiment."
        )
        + " The coarse level still accounts for "
        f"{100.0 * conds['A3_pair_type_train_mean']['relative_increase_mean'] / conds['A1_global_permutation']['relative_increase_mean']:.0f}% "
        "of the global permutation effect, so fine interval resolution is a minor "
        "part of how this checkpoint uses time.",
        "",
        "## 9. Command",
        "",
        "```bash",
        "CUDA_VISIBLE_DEVICES=1 python3 tools/s3_2_delta_diagnostics.py \\",
        "    --config agro_jepa/config/s3_2_diagnostics.yaml",
        "python3 tools/s3_2_write_reports.py",
        "```",
        "",
        f"Artifacts: `{d['artifacts']['per_sample_mse']}`, "
        f"`{d['artifacts']['permuted_deltas']}`. Runtime "
        f"{d['elapsed_seconds']:.0f} s.",
        "",
    ]
    path.write_text("\n".join(L))


